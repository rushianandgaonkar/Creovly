import fs from 'fs';
import path from 'path';
import ts from 'typescript';

function loadTsModule(filePath, mocks = {}) {
  const content = fs.readFileSync(filePath, 'utf8');
  const compiled = ts.transpileModule(content, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const moduleExports = {};
  const requireMock = (id) => {
    if (mocks[id]) return mocks[id];
    if (id === '@/config/site') return loadTsModule(path.resolve('config/site.ts'), mocks);
    if (id === '@/config/i18n') return loadTsModule(path.resolve('config/i18n.ts'), mocks);
    if (id === '@/lib/guides') return loadTsModule(path.resolve('lib/guides.ts'), mocks);
    if (id === '@/types') return {};
    throw new Error(`Cannot resolve mock for: ${id}`);
  };
  const fn = new Function('exports', 'require', 'module', compiled);
  const mod = { exports: moduleExports };
  fn(moduleExports, requireMock, mod);
  return mod.exports;
}

function getExpectedCanonicalUrls() {
  const sitemapMod = loadTsModule(path.resolve('app/sitemap.ts'), { '@/types': {} });
  const sitemapEntries = sitemapMod.default();
  return sitemapEntries.map((entry) => entry.url);
}

function verifyStaticSitemaps() {
  const outDir = path.resolve('out');
  const publicDir = path.resolve('public');
  let hasErrors = false;

  console.log('\n--- Verifying Sitemap, Robots, and Deployment Artifacts ---');

  if (!fs.existsSync(outDir)) {
    console.error('❌ Build Failure: out/ directory does not exist. Run "next build" first.');
    process.exit(1);
  }

  // 1. Fail if legacy or duplicate sitemap/robots files exist in public/
  const forbiddenPublicFiles = [
    'sitemap.xml',
    'robots.txt',
    'sitemap-0.xml',
    'sitemap_index.xml',
    'sitemap.index',
  ];
  const foundForbidden = [];
  for (const file of forbiddenPublicFiles) {
    if (fs.existsSync(path.join(publicDir, file))) {
      foundForbidden.push(file);
    }
  }
  if (foundForbidden.length > 0) {
    console.error(`❌ Build Failure: Forbidden overlapping sitemap/robots file(s) found in public/: ${foundForbidden.join(', ')}`);
    console.error('   app/sitemap.ts and app/robots.ts are the authoritative generation sources.');
    console.error('   Remove these files from public/ to avoid duplicate or conflicting build sources.');
    hasErrors = true;
  } else {
    console.log('✓ Verified public/ contains no conflicting sitemap or robots files.');
  }

  // 2. Derive expected canonical URLs dynamically from canonical route configuration
  let expectedUrls = [];
  try {
    expectedUrls = getExpectedCanonicalUrls();
    console.log(`✓ Derived ${expectedUrls.length} expected canonical URLs dynamically from app/sitemap.ts route config.`);
  } catch (err) {
    console.error(`❌ Build Failure: Could not load canonical route configuration from app/sitemap.ts: ${err.message}`);
    process.exit(1);
  }

  // 3. Verify canonical out/sitemap.xml
  const sitemapOutPath = path.join(outDir, 'sitemap.xml');
  if (!fs.existsSync(sitemapOutPath)) {
    console.error('❌ Build Failure: out/sitemap.xml was not generated by Next.js');
    hasErrors = true;
  } else {
    const sitemapContent = fs.readFileSync(sitemapOutPath, 'utf8');
    const locRegex = /<loc>(.*?)<\/loc>/g;
    const actualUrls = [];
    let match;
    while ((match = locRegex.exec(sitemapContent)) !== null) {
      actualUrls.push(match[1].trim());
    }

    // Check count
    if (actualUrls.length !== expectedUrls.length) {
      console.error(`❌ Build Failure: Sitemap URL count mismatch. Expected ${expectedUrls.length}, but found ${actualUrls.length} in out/sitemap.xml.`);
      hasErrors = true;
    }

    // Check for missing required canonical URLs
    const actualSet = new Set(actualUrls);
    const missingUrls = expectedUrls.filter((url) => !actualSet.has(url));
    if (missingUrls.length > 0) {
      console.error(`❌ Build Failure: out/sitemap.xml is missing required canonical URLs:\n   ${missingUrls.join('\n   ')}`);
      hasErrors = true;
    }

    // Check for unexpected extra URLs
    const expectedSet = new Set(expectedUrls);
    const unexpectedUrls = actualUrls.filter((url) => !expectedSet.has(url));
    if (unexpectedUrls.length > 0) {
      console.error(`❌ Build Failure: out/sitemap.xml contains unexpected extra URLs:\n   ${unexpectedUrls.join('\n   ')}`);
      hasErrors = true;
    }

    if (missingUrls.length === 0 && unexpectedUrls.length === 0 && actualUrls.length === expectedUrls.length) {
      console.log(`✓ Verified out/sitemap.xml contains all ${expectedUrls.length} expected canonical URLs without deviations.`);
    }
  }

  // 4. Verify out/robots.txt
  const robotsOutPath = path.join(outDir, 'robots.txt');
  if (!fs.existsSync(robotsOutPath)) {
    console.error('❌ Build Failure: out/robots.txt was not generated by Next.js');
    hasErrors = true;
  } else {
    const robotsContent = fs.readFileSync(robotsOutPath, 'utf8');
    const canonicalSitemapRef = 'Sitemap: https://creovly.com/sitemap.xml';
    if (!robotsContent.includes(canonicalSitemapRef)) {
      console.error(`❌ Build Failure: out/robots.txt is missing required canonical sitemap reference: "${canonicalSitemapRef}"`);
      hasErrors = true;
    } else {
      console.log('✓ Verified out/robots.txt references the canonical sitemap.');
    }

    // Ensure no legacy sitemaps are referenced in robots.txt
    const legacyRefs = ['sitemap-0.xml', 'sitemap_index.xml', 'sitemap.index'];
    for (const legacy of legacyRefs) {
      if (robotsContent.includes(legacy)) {
        console.error(`❌ Build Failure: out/robots.txt references deprecated legacy sitemap: "${legacy}"`);
        hasErrors = true;
      }
    }
  }

  // 5. Verify Cloudflare _redirects
  const redirectsOutPath = path.join(outDir, '_redirects');
  if (!fs.existsSync(redirectsOutPath)) {
    console.error('❌ Build Failure: out/_redirects is missing. Cloudflare redirects will not be deployed.');
    hasErrors = true;
  } else {
    const redirectsContent = fs.readFileSync(redirectsOutPath, 'utf8');
    const requiredRedirects = [
      '/sitemap.index /sitemap.xml 301',
      '/sitemap_index /sitemap.xml 301',
      '/sitemap_index.xml /sitemap.xml 301',
      '/sitemap-0.xml /sitemap.xml 301',
      '/sitemap /sitemap.xml 301',
    ];
    const missingRedirects = requiredRedirects.filter((rule) => !redirectsContent.includes(rule));
    if (missingRedirects.length > 0) {
      console.error(`❌ Build Failure: out/_redirects is missing required alias redirect rules:\n   ${missingRedirects.join('\n   ')}`);
      hasErrors = true;
    } else {
      console.log('✓ Verified out/_redirects contains all canonical sitemap alias redirect rules.');
    }
  }

  // 6. Ensure correct server-rendered HTML lang attribute on localized static export files
  const nonDefaultLocales = ['es', 'ja', 'fr', 'de', 'pt', 'ko', 'it'];
  let localizedHtmlFilesUpdated = 0;

  function updateHtmlLang(filePath, targetLang) {
    if (!fs.existsSync(filePath)) return;
    let content = fs.readFileSync(filePath, 'utf8');
    if (content.includes('<html lang="en"')) {
      content = content.replace('<html lang="en"', `<html lang="${targetLang}"`);
      fs.writeFileSync(filePath, content, 'utf8');
      localizedHtmlFilesUpdated++;
    }
  }

  function processDir(dirPath, targetLang) {
    if (!fs.existsSync(dirPath)) return;
    const entries = fs.readdirSync(dirPath, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dirPath, entry.name);
      if (entry.isDirectory()) {
        processDir(fullPath, targetLang);
      } else if (entry.name.endsWith('.html')) {
        updateHtmlLang(fullPath, targetLang);
      }
    }
  }

  for (const loc of nonDefaultLocales) {
    updateHtmlLang(path.join(outDir, `${loc}.html`), loc);
    processDir(path.join(outDir, loc), loc);
  }
  console.log(`✓ Verified and ensured server-rendered HTML lang attribute on ${localizedHtmlFilesUpdated} localized static pages.`);

  // 7. Clean up any stale legacy sitemap files in out/
  for (const legacy of ['sitemap-0.xml', 'sitemap_index.xml']) {
    const p = path.join(outDir, legacy);
    if (fs.existsSync(p)) {
      fs.unlinkSync(p);
      console.log(`✓ Cleaned legacy file out/${legacy}`);
    }
  }

  if (hasErrors) {
    console.error('\n❌ Build verification failed with errors. Aborting.\n');
    process.exit(1);
  }

  console.log('✓ All sitemap, robots, and redirect verification checks passed successfully.\n');
}

verifyStaticSitemaps();
