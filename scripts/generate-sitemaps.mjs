import fs from 'fs';
import path from 'path';

function verifyStaticSitemaps() {
  const outDir = path.resolve('out');

  if (!fs.existsSync(outDir)) {
    console.log('out directory does not exist yet; skipping post-build sitemap verification.');
    return;
  }

  // 1. Verify canonical out/sitemap.xml
  const sitemapOutPath = path.join(outDir, 'sitemap.xml');
  if (!fs.existsSync(sitemapOutPath)) {
    console.error('Error: out/sitemap.xml was not generated by Next.js');
    process.exit(1);
  }
  const sitemapContent = fs.readFileSync(sitemapOutPath, 'utf8');
  const locMatches = sitemapContent.match(/<loc>/g) || [];
  console.log(`✓ Verified out/sitemap.xml exists with ${locMatches.length} canonical URLs.`);

  // 2. Verify out/robots.txt
  const robotsOutPath = path.join(outDir, 'robots.txt');
  if (!fs.existsSync(robotsOutPath)) {
    console.error('Error: out/robots.txt was not generated by Next.js');
    process.exit(1);
  }
  const robotsContent = fs.readFileSync(robotsOutPath, 'utf8');
  if (!robotsContent.includes('Sitemap: https://creovly.com/sitemap.xml')) {
    console.error('Warning: out/robots.txt does not contain canonical sitemap reference.');
  } else {
    console.log('✓ Verified out/robots.txt points to canonical sitemap.');
  }

  // 3. Verify Cloudflare _redirects
  const redirectsOutPath = path.join(outDir, '_redirects');
  if (fs.existsSync(redirectsOutPath)) {
    console.log('✓ Verified out/_redirects is present for Cloudflare deployment.');
  }

  // 4. Clean up any stale legacy sitemap files in out/
  for (const legacy of ['sitemap-0.xml', 'sitemap_index.xml']) {
    const p = path.join(outDir, legacy);
    if (fs.existsSync(p)) {
      fs.unlinkSync(p);
      console.log(`✓ Cleaned legacy file out/${legacy}`);
    }
  }
}

verifyStaticSitemaps();
